#!/usr/bin/env python3
# 토큰당(노드 A) 행렬곱 바이트·시간·실효 대역폭 — kgroups-A.txt 의 묶음을 텐서 모양(gguf_head)에 맞춘 것. 230 GB/s(이 기계 DRAM 실측 ≈240)를 이상으로 본 차이.
# 형식 바이트/원소: Q5_0 22/32, Q8_0 34/32, Q6_K 210/256, IQ4_XS 136/256, IQ4_NL 18/32, BF16 2. 나뉨: TP=2 에서 노드당 절반(행 또는 열).
rows = [  # (묶음, 종류, 회/토큰, 회당 µs, 회당 MB)
    ("GDN qkv+gate Q5_0 8192행×2560", "나뉨", 35.2, 69.2, 8192*2560*22/32/1e6),
    ("ssm_out Q5_0 2560행×3072", "나뉨", 35.2, 28.1, 2560*3072*22/32/1e6),
    ("attn_q Q5_0 6144행×2560", "나뉨", 11.8, 54.2, 6144*2560*22/32/1e6),
    ("attn_output Q8_0 2560행×3072", "나뉨", 12.7, 41.6, 2560*3072*34/32/1e6),
    ("attn_k/v Q5_0 256행×2560", "나뉨", 23.5, 4.6, 256*2560*22/32/1e6),
    ("출력층 Q6_K 124160행×2560", "나뉨", 1.0, 1129.5, 124160*2560*210/256/1e6),
    ("MoE gate+up IQ4_XS 10전문가×2×320행×2560", "나뉨(전문가)", 47.0, 48.8, 10*2*320*2560*136/256/1e6),
    ("MoE down IQ4_NL 10전문가×2560행×320", "나뉨(전문가)", 47.0, 30.3, 10*2560*320*18/32/1e6),
    ("hc up Q8_0 10240행×320 (+pre)", "복제", 94.0, 19.2, 10240*320*34/32/1e6),
    ("hc down Q6_K 324행×10240", "복제", 94.0, 11.5, 324*10240*210/256/1e6),
    ("라우터·indexer q BF16 512행×2560", "복제", 58.8, 16.2, 512*2560*2/1e6),
    ("shared expert gate+up Q5_0 2×640행×2560", "복제", 47.0, 12.9, 2*640*2560*22/32/1e6),
    ("shared expert down Q5_0 2560행×640 (+꼬리, AR 기다림 포함)", "복제", 47.0, 19.6, 2560*640*22/32/1e6),
]
BW = 230.0
print(f"| 묶음 | 나뉨/복제 | ms/토큰 | MB/토큰 | 실효 GB/s | 230 GB/s 이면 ms | 차이 ms |")
print("|---|---|---:|---:|---:|---:|---:|")
tot = {"t": 0, "b": 0, "i": 0}; by = {}
for name, kind, n, us, mb in rows:
    t = n*us/1000; b = n*mb; ideal = b/BW
    tot["t"] += t; tot["b"] += b; tot["i"] += ideal
    k = kind.split("(")[0]; by.setdefault(k, [0, 0, 0]); by[k][0] += t; by[k][1] += b; by[k][2] += ideal
    print(f"| {name} | {kind} | {t:.2f} | {b:.0f} | {mb/us*1000:.0f} | {ideal:.2f} | {t-ideal:+.2f} |")
print(f"| **행렬곱 합** | | **{tot['t']:.2f}** | **{tot['b']:.0f}** | {tot['b']/tot['t']:.0f} | **{tot['i']:.2f}** | **{tot['t']-tot['i']:+.2f}** |")
for k, v in by.items():
    print(f"- {k}: {v[0]:.2f} ms, {v[1]:.0f} MB ({100*v[1]/tot['b']:.0f}% of bytes), 이상 {v[2]:.2f} ms")
